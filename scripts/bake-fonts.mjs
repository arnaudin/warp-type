/**
 * Bakes the fetched TTFs into TypeScript glyph tables under src/core/fonts/.
 *
 * Why bake at all: warping letterforms needs their outlines, and Figma's font
 * APIs only hand back TextNodes. Baking also keeps the core pure — the same
 * outlines drive the UI preview and the inserted vectors, so they can't drift.
 *
 * Output is deterministic: same TTFs in, byte-identical .ts out.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFont } from './lib/ttf.mjs';
import { CHARSET, FACES } from './faces.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'src', 'core', 'fonts');
fs.mkdirSync(outDir, { recursive: true });

const banner = '// Generated by scripts/bake-fonts.mjs — do not edit by hand.\n';
const summaries = [];

/**
 * Attribution header for a derived glyph table.
 *
 * Subsetting a font and converting its outlines to path data makes a Modified
 * Version under OFL 1.1, so each generated file has to carry the original
 * copyright and license notice and stay under that license rather than the
 * project's. The same header satisfies Apache 2.0 §4(b) for Ultra, which wants
 * modified files to state that they changed.
 */
function attribution(face, font, glyphCount) {
  const copyright = font.names.get(0) || `© the ${face.source} authors`;
  const licenseUrl = font.names.get(14);
  // Emitted as a `/*! … @license … */` legal comment so esbuild carries it into
  // dist/ — the notice has to travel with the bundle that embeds the outlines,
  // not just sit in the repo.
  const lines = [
    '/*!',
    ` * Glyph outlines derived from ${face.source}.`,
    ' *',
    ` * @license ${face.licenseName}${licenseUrl ? ` — ${licenseUrl}` : ''}`,
    ` * Copyright: ${copyright}`,
    ` * Full text: fonts/${face.dir}/${path.basename(face.license)}`,
    ` * Source:    https://raw.githubusercontent.com/google/fonts/main/${face.upstream}`,
    ` * Changes:   subset to the ${glyphCount} characters listed in scripts/faces.mjs;`,
    ' *            quadratic outlines emitted as SVG path data in font units;',
    ' *            hinting, kerning and all other tables discarded.',
    ' *',
    ' * This is a Modified Version of the font above and is distributed under that',
    " * font's license, NOT the MIT license covering the rest of this project.",
  ];
  if (face.renamed) {
    lines.push(
      ' *',
      ` * Presented to users as "${face.name}": ${face.source}'s grant carries Reserved`,
      ' * Font Names, which a Modified Version may not use as the name a user picks.',
    );
  }
  return lines.join('\n') + '\n */\n';
}

for (const face of FACES) {
  const dir = path.join(root, 'fonts', face.dir);
  const ttfName = fs.readdirSync(dir).find((f) => f.endsWith('.ttf'));
  if (!ttfName) throw new Error(`no .ttf in fonts/${face.dir} — run scripts/fetch-fonts.mjs first`);
  const font = parseFont(fs.readFileSync(path.join(dir, ttfName)));

  const entries = [];
  let missing = '';
  let points = 0;
  for (const ch of CHARSET) {
    const g = font.glyphFor(ch);
    if (!g) {
      missing += ch;
      continue;
    }
    points += (g.d.match(/[MLQ]/g) || []).length;
    entries.push(`  ${JSON.stringify(ch)}: [${g.adv}, ${JSON.stringify(g.d)}],`);
  }

  // Cap height from H's own bbox: more reliable across these faces than OS/2,
  // and it is what the layout engine measures lines in.
  const capH = font.glyphFor('H');
  const capHeight = capH && capH.yMax > 0 ? capH.yMax : Math.round(font.unitsPerEm * 0.7);
  const xH = font.glyphFor('x');
  const xHeight = xH && xH.yMax > 0 ? xH.yMax : Math.round(capHeight * 0.72);

  const src =
    banner +
    attribution(face, font, entries.length) +
    `import type { BakedFont } from './types';\n\n` +
    `export const ${face.id}: BakedFont = {\n` +
    `  id: ${JSON.stringify(face.id)},\n` +
    `  name: ${JSON.stringify(face.name)},\n` +
    `  blurb: ${JSON.stringify(face.blurb)},\n` +
    `  source: ${JSON.stringify(face.source)},\n` +
    `  license: ${JSON.stringify(face.licenseName)},\n` +
    `  unitsPerEm: ${font.unitsPerEm},\n` +
    `  capHeight: ${capHeight},\n` +
    `  xHeight: ${xHeight},\n` +
    `  ascender: ${font.ascender},\n` +
    `  descender: ${font.descender},\n` +
    `  glyphs: {\n${entries.join('\n')}\n  },\n` +
    `};\n`;

  const outFile = path.join(outDir, `${face.id}.ts`);
  fs.writeFileSync(outFile, src);
  summaries.push(
    `${face.name.padEnd(14)} ${String(entries.length).padStart(3)} glyphs · ${String(points).padStart(5)} nodes · ` +
      `upem ${font.unitsPerEm} · cap ${capHeight} · ${(src.length / 1024).toFixed(1)}KB` +
      (missing ? ` · missing ${JSON.stringify(missing)}` : ''),
  );
}

const barrel =
  banner +
  FACES.map((f) => `import { ${f.id} } from './${f.id}';`).join('\n') +
  `\nimport type { BakedFont } from './types';\n\n` +
  `export const BAKED: BakedFont[] = [${FACES.map((f) => f.id).join(', ')}];\n`;
fs.writeFileSync(path.join(outDir, 'data.ts'), barrel);

console.log(summaries.join('\n'));
console.log(`\nbaked → src/core/fonts/*.ts`);
